#!/usr/bin/env python3
"""Every figure and table for the paper, from the files the other scripts write.

  python make_figures.py            # -> figures/*.png, figures/*.pdf, figures/tables.md
Reads (whatever exists): runs_batch/ (overnight_batch.py), runs/*/result.json (flow runs),
surrogate_ws/*.pt.json + .val.npz (surrogate_ws.py), runs_batch/models/ (hold-out models),
verify_out/*/ (verify_designs.py). Missing inputs are skipped with a note.
Needs: pip install matplotlib
"""
import glob, json, os, statistics, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
OUT = os.path.join(HERE, "figures")
BATCH = os.path.abspath(os.environ.get("LDO_BATCH") or os.path.join(HERE, "runs_batch"))

# Fixed method -> colour mapping (categorical slots in fixed order; never re-assigned per figure).
COL = {"bo_warm": "#2a78d6", "bo_cold": "#eb6834", "de": "#1baf7a", "random": "#eda100", "bo_warm_static": "#6250d6"}
LBL = {"bo_warm": "BO, MLP warm start", "bo_cold": "BO, cold start", "de": "Differential evolution",
       "random": "Random search", "bo_warm_static": "BO, warm start, no online retrain"}
ORDER = ["bo_warm", "bo_warm_static", "bo_cold", "de", "random"]
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3dd"
TXT = ["# Tables for the paper\n", "Generated by make_figures.py. Simulation-level results (schematic, ideal reference), "
       "27 C unless stated.\n"]

plt.rcParams.update({"font.size": 9, "axes.edgecolor": MUTED, "axes.labelcolor": INK, "xtick.color": MUTED,
                     "ytick.color": MUTED, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6,
                     "axes.spines.top": False, "axes.spines.right": False, "legend.frameon": False,
                     "figure.dpi": 100, "savefig.dpi": 220, "lines.linewidth": 2})


def save(fig, name):
    os.makedirs(OUT, exist_ok=True)
    fig.tight_layout()
    for ext in ("png", "pdf"):
        fig.savefig(os.path.join(OUT, f"{name}.{ext}"), bbox_inches="tight")
    plt.close(fig)
    print("  figure:", f"figures/{name}.png")


def table(title, header, rows, note=None):
    TXT.append(f"\n## {title}\n")
    if note:
        TXT.append(note + "\n")
    TXT.append("| " + " | ".join(header) + " |")
    TXT.append("|" + "|".join("---" for _ in header) + "|")
    for r in rows:
        TXT.append("| " + " | ".join(str(v) for v in r) + " |")
    TXT.append("")


def read_jsonl(p):
    out = []
    try:
        for line in open(p, errors="replace"):
            try:
                out.append(json.loads(line))
            except ValueError:
                pass
    except OSError:
        pass
    return out


def med(v, fmt="{:.0f}"):
    v = [x for x in v if x is not None]
    return fmt.format(statistics.median(v)) if v else "–"


# ----------------------------------------------------------------------------- 1. baselines
def baselines():
    specs = sorted(d for d in os.listdir(BATCH) if d.startswith("gf180_")) if os.path.isdir(BATCH) else []
    if not specs:
        print("  (no runs_batch/ results yet: skipping baseline figures)"); return
    rows = []
    for spec in specs:
        runs = {}
        for done in glob.glob(os.path.join(BATCH, spec, "*", "done.json")):
            d = json.load(open(done))
            ev = read_jsonl(os.path.join(os.path.dirname(done), "evals.jsonl"))
            if ev:
                runs.setdefault(d["method"], []).append((d, ev))
        if not runs:
            continue
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.2, 2.8))
        for m in [m for m in ORDER if m in runs]:
            n = max(len(ev) for _, ev in runs[m])
            best = np.array([np.minimum.accumulate([min(e["total"], 1e3) for e in ev] + [min(e["total"], 1e3) for e in ev[-1:]] * (n - len(ev)))
                             for _, ev in runs[m]])
            npass = np.array([np.cumsum([bool(e["screen"]) for e in ev] + [0] * (n - len(ev))) for _, ev in runs[m]])
            x = np.arange(1, n + 1)
            ax1.plot(x, np.median(best, 0), color=COL[m], label=LBL[m])
            if len(best) > 1:
                ax1.fill_between(x, best.min(0), best.max(0), color=COL[m], alpha=0.12, linewidth=0)
            ax2.plot(x, np.median(npass, 0), color=COL[m], label=LBL[m])
            fps = [d["first_pass"] for d, _ in runs[m]]
            reached = [f for f in fps if f]
            rows.append([spec.replace("gf180_", "").replace("_", " / "), LBL[m], len(fps), f"{len(reached)}/{len(fps)}",
                         med(reached), med([d["best_total"] for d, _ in runs[m]], "{:.3f}"),
                         med([d["n_screen"] for d, _ in runs[m]]),
                         med([d.get("warm", {}).get("proposals_passing_screen") for d, _ in runs[m]]) if m.startswith("bo_warm") else "–"])
        ax1.set_yscale("log"); ax1.set_xlabel("SPICE evaluations (each = 5 corners)"); ax1.set_ylabel("Best objective so far")
        ax1.set_title("Best score (median, band = min–max over seeds)", fontsize=9, color=INK, loc="left")
        ax2.set_xlabel("SPICE evaluations"); ax2.set_ylabel("Designs passing all specs")
        ax2.set_title("Spec-passing designs found (median)", fontsize=9, color=INK, loc="left")
        ax2.legend(loc="upper left", fontsize=8)
        fig.suptitle(spec.replace("gf180_", "GF180MCU ").replace("_", ", "), fontsize=10, color=INK, x=0.01, ha="left")
        save(fig, f"convergence_{spec}")
    table("Optimiser comparison at equal SPICE budget",
          ["Spec (VOUT / Cout)", "Method", "Seeds", "Seeds reaching a passing design", "Evals to first pass (median)",
           "Best score (median)", "Passing designs found (median)", "MLP proposals passing in SPICE (median)"], rows,
          "Same objective, search box and budget for every method. For warm start the MLP was trained with no data at "
          "that (VOUT, Cout); MLP proposals count toward the budget.")


# ----------------------------------------------------------------------------- 2. end-to-end flow
def flow():
    f = os.path.join(BATCH, "flow_summary.json")
    if not os.path.exists(f):
        print("  (no flow_summary.json yet: skipping end-to-end table)"); return
    res = json.load(open(f))
    rows = []
    for mode in ("cold", "warm"):
        rr = [r for r in res if r["mode"] == mode]
        if rr:
            rows.append([mode, len(rr), f"{sum(r['status'] == 'met_spec' for r in rr)}/{len(rr)}",
                         med([r["first_pass"] for r in rr]), med([r["evaluations"] for r in rr]),
                         med([r["runtime_s"] / 60 for r in rr], "{:.1f}")])
    table("End-to-end flow, GF180 3.3 V / 4 µF (one attempt per run)",
          ["Start", "Runs", "Met spec after verification", "Evals to first screened pass (median)",
           "Total evals (median)", "Runtime, min (median)"], rows)


# ----------------------------------------------------------------------------- 3. portability (all flow runs)
def portability():
    rows, agg = [], {}
    for f in glob.glob(os.path.join(HERE, "runs", "*", "result.json")) + glob.glob(os.path.join(BATCH, "flow", "*", "result.json")):
        try:
            r = json.load(open(f))
        except ValueError:
            continue
        s = r.get("spec", {})
        if r.get("status") not in ("met_spec", "no_design_met_spec") or r.get("evaluations", 0) < 50:
            continue
        k = (s.get("pdk"), s.get("vout"), s.get("cout_uF"), (r.get("warm_start") or {}).get("mode", "cold"))
        agg.setdefault(k, []).append(r)
    for (pdk, v, c, mode), rr in sorted(agg.items(), key=lambda t: tuple(str(x) for x in t[0])):
        ok = [r for r in rr if r["status"] == "met_spec"]
        rows.append([pdk, v, c, mode, len(rr), f"{len(ok)}/{len(rr)}", med([r["evaluations"] for r in rr]),
                     med([r["runtime_s"] / 60 for r in rr], "{:.1f}"),
                     max((r["design"]["worst_margin"] for r in ok), default="–"),
                     min((r["design"]["area_um2"] for r in ok), default="–")])
    if rows:
        table("Same flow across PDKs and specs (all flow runs with at least 50 evaluations, single attempts)",
              ["PDK", "VOUT (V)", "Cout (µF)", "Start", "Runs", "Met spec", "Evals (median)", "Runtime, min (median)",
               "Best worst-case margin", "Smallest passing area (µm²)"], rows,
              "No code changes between PDKs except the device table in ldo_pdk.py.")
    else:
        print("  (no flow result.json files: skipping portability table)")


# ----------------------------------------------------------------------------- 4. surrogate accuracy
def surrogate():
    import surrogate_ws as W
    rows = []
    for mj in sorted(glob.glob(os.path.join(HERE, "surrogate_ws", "*.pt.json"))):
        m = json.load(open(mj))
        r2 = m.get("val_r2") or {}
        rows.append([os.path.basename(mj)[:-8], "validation (whole run folders held out)", m.get("n_train"), m.get("n_val")]
                    + [("–" if r2.get(t) is None else f"{r2[t]:.3f}") for t in W.TARGETS])
        if m.get("test_r2"):
            t2 = m["test_r2"]
            rows.append([os.path.basename(mj)[:-8], "TEST: dataset test split (never trained on)", m.get("n_train"),
                         m.get("n_test")] + [("–" if t2.get(t) is None else f"{t2[t]:.3f}") for t in W.TARGETS])
        vz = mj[:-5] + ".test.npz"           # parity plot on the held-out test set if there is one
        if not os.path.exists(vz):
            vz = mj[:-5] + ".val.npz"
        if os.path.exists(vz):
            z = np.load(vz)
            fig, axs = plt.subplots(1, 4, figsize=(8.0, 2.2))
            for ax, t, unit in zip(axs, ["psrr", "pm", "iq", "line"], ["dB", "deg", "µA", "mV"]):
                j = W.TARGETS.index(t)
                y, p = z["y"][:, j], z["p"][:, j]
                ok = ~np.isnan(y); y, p = y[ok], p[ok]       # masked (failed) measurements have no label
                lo, hi = np.percentile(np.r_[y, p], [0.5, 99.5])
                ax.plot([lo, hi], [lo, hi], color=MUTED, linewidth=1)
                ax.scatter(y, p, s=6, color=COL["bo_warm"], alpha=0.35, linewidths=0)
                ax.set_xlim(lo, hi); ax.set_ylim(lo, hi)
                ax.set_title(f"{t.upper() if t != 'line' else 'Line reg.'} ({unit})", fontsize=9, color=INK, loc="left")
                ax.set_xlabel("SPICE", fontsize=8)
            axs[0].set_ylabel("MLP prediction", fontsize=8)
            save(fig, "surrogate_parity_" + os.path.basename(mj)[:-8])
    # unseen-spec accuracy of the hold-out models: predict the spec they never saw
    for mp in sorted(glob.glob(os.path.join(BATCH, "models", "holdout_*.pt"))):
        meta = json.load(open(mp + ".json"))
        ex = meta.get("excluded") or []
        if not ex:
            continue
        v, c = ex[0]
        X, Y, S, _, _ = W.load_runs([os.path.join(HERE, "runs")], "gf180")
        sel = [i for i, s in enumerate(S) if abs(s[0] - v) < 1e-6 and abs(s[1] - c) < 1e-6]
        src = "flow runs"
        if len(sel) < 30:                    # spec never run by the flow: use the batch's own simulations
            X, Y, S, _, _ = W.load_runs([os.path.join(BATCH, f"gf180_{v:g}V_{c:g}uF")], "gf180")
            sel, src = list(range(len(X))), "batch simulations"
        if len(sel) < 30:
            continue
        model = W.Surrogate.load(mp)
        Xs, Ys = X[sel], Y[sel]
        P = model.predict(Xs)
        r2s = W.r2_scores(Ys, P)              # NaN-safe: masked PM/PSRR placeholders are skipped
        r2 = ["–" if r2s[t] is None else f"{r2s[t]:.3f}" for t in W.TARGETS]
        rows.append([os.path.basename(mp)[:-3], f"unseen spec {v:g} V / {c:g} µF ({src})", meta.get("n_train"), len(sel)] + r2)
    if rows:
        table("Surrogate accuracy (R², on the model's transformed scale)",
              ["Model", "Test set", "Train rows", "Test rows"] + W.TARGETS, rows,
              "Hold-out models never saw any data at the test spec; R² there measures generalisation to a new spec.")
    else:
        print("  (no surrogate models yet: skipping accuracy table)")


# ----------------------------------------------------------------------------- 5. warm-start proposals vs SPICE
def proposals():
    pr, sim = [], []
    for ws in glob.glob(os.path.join(BATCH, "gf180_*", "bo_warm*", "warm_seeds.json")):
        rows = json.load(open(ws)).get("rows", [])
        ev = {}
        for e in read_jsonl(os.path.join(os.path.dirname(ws), "evals.jsonl")):
            ev.setdefault(tuple(round(v, 4) for v in e["x"]), e)
        for r in rows:
            e = ev.get(tuple(round(v, 4) for v in r["x"]))
            if e and e.get("m"):
                pr.append(r); sim.append(e)
    if not pr:
        print("  (no warm-start runs yet: skipping proposal figure)"); return
    fig, axs = plt.subplots(1, 2, figsize=(5.6, 2.6))
    for ax, t, unit in zip(axs, ["psrr", "pm"], ["dB", "deg"]):
        y = [e["m"][t] for e in sim]; p = [r["pred"][t] for r in pr]
        lo, hi = min(y + p), max(y + p)
        ax.plot([lo, hi], [lo, hi], color=MUTED, linewidth=1)
        for kind, mk in (("init", "o"), ("online", "s")):
            idx = [i for i, r in enumerate(pr) if r["kind"] == kind]
            if not idx:
                continue
            ax.scatter([y[i] for i in idx], [p[i] for i in idx], s=14, marker=mk, color=COL["bo_warm"],
                       alpha=0.6 if kind == "init" else 0.95, linewidths=0, label="initial proposals" if kind == "init" else "online proposals")
        ax.set_xlabel(f"SPICE {t.upper()} ({unit})"); ax.set_title(f"{t.upper()}: MLP vs SPICE", fontsize=9, color=INK, loc="left")
    axs[0].set_ylabel("MLP prediction"); axs[0].legend(fontsize=7, loc="lower right")
    save(fig, "warmstart_pred_vs_sim")
    rows = []
    for kind in ("init", "online"):
        idx = [i for i, r in enumerate(pr) if r["kind"] == kind]
        if not idx:
            continue
        pp = [i for i in idx if r_margin(pr[i]) > 0]
        rows.append([kind, len(idx), f"{sum(sim[i]['screen'] for i in idx)}/{len(idx)}",
                     f"{sum(sim[i]['screen'] for i in pp)}/{len(pp)}" if pp else "–",
                     f"{np.mean([abs(pr[i]['pred']['psrr'] - sim[i]['m']['psrr']) for i in idx]):.2f}",
                     f"{np.mean([abs(pr[i]['pred']['pm'] - sim[i]['m']['pm']) for i in idx]):.2f}"])
    table("MLP-proposed points, checked in SPICE (all warm-start batch runs)",
          ["Proposal type", "Simulated", "Passed screen", "Passed, of those predicted to pass", "PSRR abs. error (dB)",
           "PM abs. error (deg)"], rows)


def r_margin(r):
    return r.get("pred_margin_spec", r.get("pred_margin", 0))


# ----------------------------------------------------------------------------- 6. robustness
def robustness():
    sums = sorted(glob.glob(os.path.join(HERE, "verify_out", "*", "summary.json")))
    if not sums:
        print("  (no verify_out/ yet: skipping robustness tables)"); return
    trows, mrows = [], []
    for s in sums:
        j = json.load(open(s))
        nm = f"{j['pdk']} {j['vout']} V / {j['cout_uF']} µF"
        for t, v in (j.get("temperature") or {}).items():
            trows.append([nm, f"{float(t):g}", "PASS" if v["all_pass"] else "FAIL: " + ", ".join(v["failing"]),
                          f"{v['worst_psrr']:.1f}" if v["worst_psrr"] is not None else "–",
                          f"{v['worst_pm']:.1f}" if v["worst_pm"] is not None else "–"])
        mc = j.get("mc")
        if mc and "yield_pct" in mc:
            mrows.append([nm, mc["simulated"], f"{mc['yield_pct']}%", f"{mc['vout_sigma_mV']:.2f}",
                          f"{mc['psrr_mean']:.1f} ± {mc['psrr_sigma']:.2f}",
                          ", ".join(f"{k}: {v}" for k, v in mc["fail_counts"].items()) or "none"])
            csvp = os.path.join(os.path.dirname(s), "mc.csv")
            if os.path.exists(csvp):
                import csv
                rr = [r for r in csv.DictReader(open(csvp)) if r.get("failed") == "False"]
                fig, axs = plt.subplots(1, 2, figsize=(5.6, 2.3))
                for ax, k, lab, sc in ((axs[0], "vout", "VOUT (mV from nominal)", 1e3), (axs[1], "psrr", "PSRR at 10 kHz (dB)", 1)):
                    vals = [float(r[k]) * sc - (j["vout"] * 1e3 if k == "vout" else 0) for r in rr]
                    ax.hist(vals, bins=24, color=COL["bo_warm"], edgecolor="white", linewidth=0.6)
                    ax.set_xlabel(lab); ax.grid(axis="x", visible=False)
                axs[0].set_ylabel("Samples")
                fig.suptitle(f"Monte Carlo mismatch, {nm}, tt 27 C: yield {mc['yield_pct']}% of {mc['simulated']}",
                             fontsize=9, color=INK, x=0.01, ha="left")
                save(fig, f"mc_{os.path.basename(os.path.dirname(s))}")
        elif mc:
            mrows.append([nm, "–", "not run: " + mc.get("error", ""), "–", "–", "–"])
    if trows:
        table("Temperature sweep (all five process corners at each temperature)",
              ["Design", "Temp (°C)", "Result", "Worst PSRR (dB)", "Worst PM (deg)"], trows)
    if mrows:
        table("Monte Carlo mismatch (tt, 27 °C)", ["Design", "Samples", "Yield", "VOUT σ (mV)", "PSRR (dB)", "Failures"], mrows)


def sky130_flow():
    f = os.path.join(HERE, "runs_sky130_compare", "summary.json")
    if not os.path.exists(f):
        print("  (no runs_sky130_compare/summary.json: skipping SKY130 warm/cold table)"); return
    res = json.load(open(f))
    names = {"cold": "cold", "warm_new": "warm, MLP trained on runs + dataset",
             "warm_old": "warm, MLP trained on runs only"}
    rows = []
    for arm in ("cold", "warm_new", "warm_old"):
        rr = [r for r in res if r["arm"] == arm]
        if not rr:
            continue
        ok = []
        for r in rr:
            try:
                d = json.load(open(r["result"]))
            except (OSError, ValueError):
                continue
            if d.get("status") == "met_spec":
                ok.append(d["design"]["worst_margin"])
        rows.append([names[arm], len(rr), f"{sum(r['status'] == 'met_spec' for r in rr)}/{len(rr)}",
                     med([r["first_pass"] for r in rr]), med([r["evaluations"] for r in rr]),
                     med([r["runtime_s"] / 60 for r in rr], "{:.1f}"), max(ok, default="–")])
    table("End-to-end flow, SKY130 3.3 V / 4 µF (one attempt per run, same seeds per arm)",
          ["Start", "Runs", "Met spec after verification", "Evals to first screened pass (median)",
           "Total evals (median)", "Runtime, min (median)", "Best worst-case margin"], rows,
          "Both MLPs were trained on SKY130 3.3 V / 4 µF data: this is warm start from prior data at the "
          "same spec, not an unseen-spec test (unlike the GF180 hold-out models).")


def main():
    for f in (baselines, flow, sky130_flow, portability, surrogate, proposals, robustness):
        print(f"[{f.__name__}]")
        try:
            f()
        except Exception as e:
            print(f"  {f.__name__} failed: {e!r}")
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, "tables.md"), "w").write("\n".join(TXT) + "\n")
    print("tables: figures/tables.md")


if __name__ == "__main__":
    main()
